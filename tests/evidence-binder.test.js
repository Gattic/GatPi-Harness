"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { EvidenceStore, createEvidencePacket, extractClaims, bindClaims, captureVerificationEvidence, visualComparisonMetadata, visualEvidenceReferences } = require("../src/evidence-binder");
const { captureTreeFingerprint } = require("../src/tree-fingerprint.js");
const { tmpFixture } = require("./helpers/tmp-fixture");

const evidence = createEvidencePacket({ source: "test", ok: true, confidence: 0.9, commands: ["node tests/foo.test.js"], files: ["src/foo.js"], summary: "tests passed for foo" });
assert.equal(evidence.ok, true);
const visualEvidence = { visual: { results: [{ caseId: "frame", kind: "tui-frame", status: "pass", ok: true, reasonCode: "within-threshold", actual: { artifactRef: "artifact_0123456789abcdef0123456789abcdef", digest: `sha256:${"a".repeat(64)}` }, baseline: { digest: `sha256:${"b".repeat(64)}` }, identity: { sourceFingerprint: `sha256:${"c".repeat(64)}`, captureConfigHash: `sha256:${"d".repeat(64)}` }, provider: { providerId: "tui-frame", runtimeVersion: "1.0.0" } }] } };
const visualPacket = createEvidencePacket({ source: "verification-center", ok: true, evidence: visualEvidence });
assert.equal(visualComparisonMetadata(visualEvidence)[0].caseId, "frame");
assert(visualEvidenceReferences(visualEvidence).some((ref) => ref.startsWith("visual:frame:")));
assert.equal(visualPacket.metadata.visualComparisons.length, 1);
assert.equal(JSON.stringify(visualPacket).includes("frame body"), false);
assert.ok(extractClaims("Implemented foo. Tests passed.").length >= 1);
const bound = bindClaims("Implemented foo. Tests passed.", [evidence]);
assert.equal(bound.ok, true);
const unsupported = bindClaims("Verified bar with no regressions.", []);
assert.equal(unsupported.ok, false);
const tmp = tmpFixture("pi-evidence-");
fs.writeFileSync(path.join(tmp, ".gitignore"), ".pi/\n");
fs.writeFileSync(path.join(tmp, "source.js"), "module.exports = 1;\n");
for (const args of [["init", "-q"], ["config", "user.email", "fixture@example.invalid"], ["config", "user.name", "Fixture"], ["add", "."], ["commit", "-qm", "fixture"]]) assert.equal(spawnSync("git", args, { cwd: tmp }).status, 0);
const missingCapture = captureVerificationEvidence(tmp);
assert.equal(missingCapture.captured, false, "missing verification evidence is an actionable result, not a tool error");
assert.equal(missingCapture.outcome, "not-applicable");
assert.equal(missingCapture.status, "not-applicable");
assert.equal(missingCapture.ok, null);
assert.equal(missingCapture.reasonCode, "verification-prerequisite-missing");
assert.match(missingCapture.message, /then retry captureVerification/);
assert.deepEqual(missingCapture.next, { tool: "verification_center", parameters: { operation: "run", profile: "changed" } });

const store = new EvidenceStore({ cwd: tmp });
store.saveEvidence(evidence);
assert.equal(store.status().evidenceCount, 1);
assert.equal(store.status().latest.freshness.status, "current");
assert.equal(store.status().latest.evidence, undefined, "default status returns a bounded packet summary");
assert.ok(store.status({ detail: true }).latestDetail.commands.length, "explicit detailed status retains bounded command inspection");
assert.equal(store.validateEvidenceId(evidence.id).ok, true, "registered passing packets can substantiate roadmap verification");
assert.equal(store.validateEvidenceId("fabricated-evidence").ok, false, "arbitrary strings are not verifier evidence");
assert.equal(store.validateEvidenceId("../outside").reason, "invalid-evidence-id", "evidence lookup rejects path traversal");
const legacyRoot = tmpFixture("pi-evidence-legacy-id-");
const legacyStore = new EvidenceStore({ cwd: legacyRoot });
const legacyId = "legacy/custom";
fs.mkdirSync(path.join(legacyStore.root, "packets", "legacy"), { recursive: true });
fs.writeFileSync(path.join(legacyStore.root, "packets", `${legacyId}.json`), JSON.stringify({ id: legacyId, ok: true, fingerprint: "legacy" }));
fs.mkdirSync(legacyStore.root, { recursive: true });
fs.writeFileSync(legacyStore.ledgerFile(), `${JSON.stringify({ id: legacyId, fingerprint: "legacy" })}\n`);
assert.doesNotThrow(() => legacyStore.status(), "legacy custom IDs are quarantined instead of breaking the evidence store");
assert.equal(legacyStore.status().latest, null);
const failingEvidence = store.saveEvidence(createEvidencePacket({ source: "test", ok: false, summary: "failed verification" }));
assert.equal(store.validateEvidenceId(failingEvidence.id).reason, "evidence-not-passing");
fs.writeFileSync(store.packetFile(failingEvidence.id), `${JSON.stringify({ ...failingEvidence, ok: true }, null, 2)}\n`);
assert.equal(store.validateEvidenceId(failingEvidence.id).reason, "evidence-fingerprint-mismatch", "tampering cannot turn failed evidence into passing proof");
assert.equal(store.checkText("Tests passed for foo.").ok, true);
const verificationDir = path.join(tmp, ".pi", "verification-center");
fs.mkdirSync(verificationDir, { recursive: true });
fs.writeFileSync(path.join(verificationDir, "latest.json"), JSON.stringify({ commands: ["node tests/foo.test.js"], evidence: { ok: true, confidence: 0.9, summary: "verified foo", createdAt: "2026-08-09T20:00:00.000Z", tree: captureTreeFingerprint(tmp), changeSet: { changedFiles: ["src/foo.js"] } } }));
const captured = captureVerificationEvidence(tmp, { store });
assert.equal(captured.source, "verification-center");
assert.equal(captured.ok, true);
assert.equal(store.status().evidenceCount, 3, "available Verification Center evidence is still persisted as before");
fs.writeFileSync(path.join(tmp, "source.js"), "module.exports = 2;\n");
assert.equal(store.validateEvidenceId(captured.id).reason, "stale-tree", "proof packets cannot substantiate a changed working tree");
const staleClaim = store.checkText("Tests passed for foo.");
assert.equal(staleClaim.ok, false, "claim binding excludes stale-tree packets");
assert.equal(staleClaim.evidenceCohort.current, 0);
const staleCapture = captureVerificationEvidence(tmp, { store });
assert.equal(staleCapture.captured, false);
assert.equal(staleCapture.reasonCode, "stale-tree");
assert.equal(store.status().evidenceCount, 3, "stale Verification Center evidence is not recaptured with a newer timestamp");

// Empty packets: a capture that carries nothing is refused, and an empty packet
// saved before that check cannot pass as current proof. With ok and confidence
// set, its score alone (0.58) used to clear the claim-support threshold.
assert.throws(() => store.saveEvidence({ ok: true, confidence: 0.9 }), /Evidence packet has no content/, "a packet without content is refused");
assert.throws(() => store.saveEvidence({ ok: true, summary: "   ", commands: [], metadata: {} }), /no content/, "blank fields are not content");
assert.throws(() => store.saveEvidence(createEvidencePacket(JSON.stringify({ ok: true, summary: "tests passed for foo" }))), /no content/, "an unparsed JSON string reads as an empty packet and is refused");
assert.equal(store.status().evidenceCount, 3, "refused packets are not registered");
const currentTree = captureTreeFingerprint(tmp);
const legacyEmpty = createEvidencePacket({ ok: true, confidence: 0.9, tree: currentTree });
fs.writeFileSync(store.packetFile(legacyEmpty.id), `${JSON.stringify(legacyEmpty, null, 2)}\n`);
fs.appendFileSync(store.ledgerFile(), `${JSON.stringify({ id: legacyEmpty.id, fingerprint: legacyEmpty.fingerprint })}\n`);
assert.equal(store.validateEvidenceId(legacyEmpty.id).reason, "evidence-packet-empty", "an empty packet already on disk cannot substantiate verification");
assert.equal(store.validateEvidenceId(legacyEmpty.id, { requireOk: false }).reason, "evidence-packet-empty");
assert.equal(store.status().latest.id, legacyEmpty.id);
assert.deepEqual(store.status().latest.freshness, { status: "empty-packet", currentTree: true, gatingSafe: false }, "status never reports an empty packet as current");
const emptyClaim = store.checkText("Tests passed for foo.");
assert.equal(emptyClaim.ok, false, "an empty packet cannot support a claim");
assert.equal(emptyClaim.evidenceCohort.current, 0);
const control = store.saveEvidence({ ok: true, confidence: 0.9, summary: "tests passed for foo", tree: currentTree });
assert.equal(store.validateEvidenceId(control.id).reason, "current-evidence-packet", "the same packet with content on the same tree is current proof");
assert.equal(store.checkText("Tests passed for foo.").ok, true);
console.log("evidence-binder tests passed");
