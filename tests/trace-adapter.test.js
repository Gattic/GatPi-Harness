"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { TRACE_CATEGORIES, createTraceRuntime, MemoryJsonStorage, RecordingSink, normalizeTraceEvent } = require("../src/trace-observability");

const storage = new MemoryJsonStorage();
const sink = new RecordingSink();
const trace = createTraceRuntime({ storage, sink, clock: () => 42 });
const event = trace.emit(normalizeTraceEvent({ type: "startup", category: "session" }));
assert(event.timestamp);
assert.equal(storage.readJsonl("trace/events").length, 1);
assert(sink.events.some((e) => e.type === "trace.event"));
const { ALLOWED_EVENTS, createCodeContextTelemetry } = require("../src/code-context-telemetry.js");
const disabled = createTraceRuntime({ enabled: false, storage: new MemoryJsonStorage(), sink: new RecordingSink() });
assert.equal(disabled.emit({ name: "x" }).enabled, false);
assert.ok(TRACE_CATEGORIES.includes("retrieval"));
assert.equal(normalizeTraceEvent({ category: "retrieval", name: "query.classified" }).category, "retrieval");
for (const name of ["query.classified", "budget.planned", "provider.started", "provider.completed", "provider.degraded", "candidates.retrieved", "candidates.deduped", "candidates.ranked", "candidates.selected", "context.packed", "content.ref_reused", "content.expanded", "tests.proposed", "tests.executed", "edit.localized", "verification.linked"]) assert.ok(ALLOWED_EVENTS.has(name), `missing telemetry event ${name}`);
const emitted = [];
const telemetry = createCodeContextTelemetry({ emit: (event) => emitted.push(event), sessionId: "s1", projectId: "p1" });
telemetry.emit("content.expanded", { queryId: "q1", path: "src/a.js", content: "SECRET SOURCE", snippet: "hidden" });
assert.equal(emitted.length, 1);
assert.equal(emitted[0].payload.content, undefined);
assert.equal(emitted[0].payload.snippet, undefined);
assert.equal(emitted[0].sessionId, "s1");
const traceExtension = fs.readFileSync(path.join(process.cwd(), ".pi", "extensions", "trace-observability", "index.ts"), "utf8");
assert.match(traceExtension, /code-context:retrieval/);
assert.match(traceExtension, /retrievalUnsubscribe\?\.\(\)/);
assert.match(traceExtension, /session_start/);
assert.match(traceExtension, /session_shutdown/);
assert.doesNotMatch(traceExtension, /retrievalMeta[^\n]*ctx/, "retrieval callbacks must retain stable ids, not a Pi context");
console.log("trace-adapter tests passed");
