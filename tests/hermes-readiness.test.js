#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { policyFromEnv, timeoutFor, identityFor, stateFile, readinessStatus, shouldAttempt, recordOutcome } = require("../src/hermes-readiness.js");
const { tmpFixture } = require("./helpers/tmp-fixture");

const tmp = tmpFixture("pi-hermes-readiness-");
const bin = path.join(tmp, "hermes");
fs.writeFileSync(bin, "#!/usr/bin/env node\nprocess.exit(0);\n"); fs.chmodSync(bin, 0o755);
const options = { bin, provider: "private-provider-name", model: "private-model-name", policy: { proofTtlMs: 1000, failureBackoffMs: 5000 } };
const identity = identityFor(options);
assert.equal(identity.eligible, true);
assert.equal(timeoutFor("prompt", 999999, policyFromEnv()), 10000, "shared prompt timeout defaults to ten seconds");
assert.equal(timeoutFor("controller", 999999, policyFromEnv()), 30000, "goal-controller timeout defaults above the observed 9.4-second p90");
const configuredPromptPolicy = policyFromEnv({ PI_HERMES_PROMPT_TIMEOUT_MS: "60000" });
assert.equal(timeoutFor("prompt", 999999, configuredPromptPolicy), 60000, "prompt timeout can be raised to the documented sixty-second ceiling");
const configuredControllerPolicy = policyFromEnv({ PI_HERMES_CONTROLLER_TIMEOUT_MS: "45000" });
assert.equal(timeoutFor("controller", 999999, configuredControllerPolicy), 45000, "goal-controller timeout has an independent configurable ceiling");
assert.equal(readinessStatus(tmp, options).authReady, false);
recordOutcome(tmp, options, { operation: "auth", outcome: "succeeded", category: "ready", durationMs: 10 });
recordOutcome(tmp, options, { operation: "curation-probe", outcome: "succeeded", category: "ready", durationMs: 12 });
const ready = readinessStatus(tmp, options);
assert.equal(ready.authReady, true);
assert.equal(ready.curationReady, true);
recordOutcome(tmp, options, { operation: "prompt", outcome: "failed", category: "transport", durationMs: 20 });
const backedOff = shouldAttempt(tmp, options);
assert.equal(backedOff.allowed, false);
assert.equal(backedOff.reason, "backoff-active");
recordOutcome(tmp, options, { operation: "advisory", outcome: "skipped", category: "unavailable" });
assert.equal(shouldAttempt(tmp, options).allowed, false, "a skipped automatic retry must not clear the active failure cooldown");
assert.equal(shouldAttempt(tmp, { ...options, force: true }).allowed, true, "explicit doctor/manual attempts may bypass the cooldown");
const expired = readinessStatus(tmp, { ...options, now: Date.now() + 6000 });
assert.equal(expired.authReady, false, "old doctor proof must not remain current");
assert.equal(expired.curationReady, false);
const file = stateFile(tmp); const text = fs.readFileSync(file, "utf8");
assert.equal(fs.statSync(file).mode & 0o777, 0o600);
assert.equal(fs.statSync(path.dirname(file)).mode & 0o777, 0o700);
assert.doesNotMatch(text, /private-provider-name|private-model-name|prompt text|query|response|\/tmp\//, "shared readiness state is category/hash only");
const symlinkRepo = path.join(tmp, "symlink-repo"); const outside = path.join(tmp, "outside");
fs.mkdirSync(path.join(symlinkRepo, ".pi"), { recursive: true }); fs.mkdirSync(outside); fs.symlinkSync(outside, path.join(symlinkRepo, ".pi", "hermes-advisory"), "dir");
recordOutcome(symlinkRepo, options, { operation: "auth", outcome: "succeeded", category: "ready" });
assert.equal(fs.readdirSync(outside).length, 0, "shared readiness writes must not follow a state-directory symlink");
console.log("hermes readiness checks passed");
